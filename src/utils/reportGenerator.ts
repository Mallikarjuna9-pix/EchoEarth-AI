import { AnalysisResult } from "../types";

export function generateTextReport(result: AnalysisResult): string {
  const lines: string[] = [
    "==================================================",
    "          ECHOEARTH AI — REUSE BLUEPRINT          ",
    "       Give Every Waste Item a Second Life       ",
    "==================================================",
    "",
    `OBJECT:      ${result.object}`,
    `MATERIAL:    ${result.material}`,
    `CONFIDENCE:  ${result.confidence}`,
    `CONDITION:   ${result.condition}`,
    "",
    "STRUCTURAL REUSE POTENTIAL:",
    result.reusePotential,
    "",
    "--------------------------------------------------",
    "              SAFETY & CAUTION NOTES              ",
    "--------------------------------------------------",
    ...result.safetyNotes.map((note) => `• [!] ${note}`),
    "",
    `RESPONSIBLE END-OF-LIFE DISPOSAL:`,
    result.disposalAdvice,
    "",
    "==================================================",
    "             THREE REUSE INVENTIONS               ",
    "==================================================",
    "",
  ];

  result.ideas.forEach((idea, index) => {
    lines.push(
      `[PROJECT 0${index + 1}] ${idea.title.toUpperCase()}`,
      `Category:       ${idea.category}`,
      `Difficulty:     ${idea.difficulty} | Time: ${idea.time}`,
      `Estimated Cost: ${idea.estimatedCostUSD}`,
      `Waste Diverted: ~${idea.estimatedGramsSaved}g | Saved vs New: ~$${idea.estimatedDollarsSaved}`,
      "",
      `Description:`,
      idea.description,
      "",
      "Materials Needed:",
      ...idea.materials.map((m) => `  - ${m}`),
      "",
      "Tools Needed:",
      ...idea.tools.map((t) => `  - ${t}`),
      "",
      "Step-by-Step Instructions:",
      ...idea.steps.map((s, i) => `  ${i + 1}. ${s}`),
      ""
    );

    if (idea.proTips && idea.proTips.length > 0) {
      lines.push("Craftsman Pro Tips:", ...idea.proTips.map((tip) => `  * ${tip}`), "");
    }

    lines.push(`Environmental Impact:`, `  ${idea.impact}`, "");
    lines.push("--------------------------------------------------", "");
  });

  lines.push(
    "==================================================",
    "               CIRCULAR LIVING TIP                ",
    "==================================================",
    result.overallTip,
    "",
    `Natural Decomposition Timeline: ${result.environmentalContext.estimatedDecompositionYears}`,
    `Lifecycle Insight: ${result.environmentalContext.lifecycleNote}`,
    `Closing the Loop: ${result.environmentalContext.circularTip}`,
    "Generated by EchoEarth AI. Always exercise personal caution with tools and chemicals.",
    `Date: ${new Date().toLocaleDateString()} | © 2026 EchoEarth AI. All rights reserved.`
  );

  return lines.join("\n");
}

export function downloadReportFile(result: AnalysisResult) {
  const content = generateTextReport(result);
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  const sanitizedName = result.object.toLowerCase().replace(/[^a-z0-9]/g, "-").slice(0, 30);
  anchor.download = `EchoEarth-Blueprint-${sanitizedName || "project"}.txt`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
